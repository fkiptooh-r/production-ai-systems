"""Generate the secrets for the local Langfuse and the keys the tracer needs.

    uv run langfuse-setup        # once, before the first `docker compose up -d`

Writes two gitignored files:
- langfuse/.env: database, ClickHouse, Redis and MinIO passwords, signing keys, and the
  admin login. Docker Compose reads it when you start Langfuse.
- the repo-root .env: LANGFUSE_HOST, LANGFUSE_PUBLIC_KEY, LANGFUSE_SECRET_KEY. The tracer
  in 02 and lab 01 read it, so their spans are exported.

An existing langfuse/.env is never overwritten: the databases were initialised with those
passwords, and new ones would lock you out. Delete the Docker volumes first if you want to
start again (`docker compose down -v`).
"""

import secrets
import sys
from pathlib import Path

PROJECT_DIR = Path(__file__).resolve().parents[2]
COMPOSE_ENV = PROJECT_DIR / "langfuse" / ".env"
ROOT_ENV = PROJECT_DIR.parent / ".env"
ROOT_ENV_EXAMPLE = PROJECT_DIR.parent / ".env.example"
# 127.0.0.1, not localhost: on Windows, localhost tries IPv6 first and adds seconds per request.
HOST = "http://127.0.0.1:3000"
ADMIN_EMAIL = "admin@langfuse.local"


def compose_env() -> dict[str, str]:
    return {
        "POSTGRES_PASSWORD": secrets.token_hex(16),
        "CLICKHOUSE_PASSWORD": secrets.token_hex(16),
        "REDIS_AUTH": secrets.token_hex(16),
        "MINIO_ROOT_PASSWORD": secrets.token_hex(16),
        "SALT": secrets.token_hex(16),
        "ENCRYPTION_KEY": secrets.token_hex(32),  # Langfuse requires exactly 64 hex chars
        "NEXTAUTH_SECRET": secrets.token_hex(32),
        "LANGFUSE_PUBLIC_KEY": "pk-lf-" + secrets.token_hex(16),
        "LANGFUSE_SECRET_KEY": "sk-lf-" + secrets.token_hex(16),
        "LANGFUSE_ADMIN_EMAIL": ADMIN_EMAIL,
        "LANGFUSE_ADMIN_PASSWORD": secrets.token_urlsafe(18),
    }


def read_env(path: Path) -> dict[str, str]:
    values = {}
    if path.exists():
        for line in path.read_text(encoding="utf-8").splitlines():
            if "=" in line and not line.lstrip().startswith("#"):
                key, _, value = line.partition("=")
                values[key.strip()] = value.strip()
    return values


def set_keys(path: Path, updates: dict[str, str], template: Path | None = None) -> None:
    """Set KEY=value lines in an env file, keeping every other line (and comments) as is."""
    if path.exists():
        lines = path.read_text(encoding="utf-8").splitlines()
    elif template and template.exists():
        lines = template.read_text(encoding="utf-8").splitlines()
    else:
        lines = []
    remaining = dict(updates)
    for i, line in enumerate(lines):
        key = line.partition("=")[0].strip()
        if key in remaining and not line.lstrip().startswith("#"):
            lines[i] = f"{key}={remaining.pop(key)}"
    lines += [f"{key}={value}" for key, value in remaining.items()]
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    if COMPOSE_ENV.exists():
        values = read_env(COMPOSE_ENV)
        print(f"{COMPOSE_ENV.relative_to(PROJECT_DIR.parent)} exists; keeping its secrets.")
    else:
        values = compose_env()
        COMPOSE_ENV.write_text(
            "# Generated by `uv run langfuse-setup`. Never commit.\n"
            + "".join(f"{k}={v}\n" for k, v in values.items()),
            encoding="utf-8",
        )
        print(f"Wrote {COMPOSE_ENV.relative_to(PROJECT_DIR.parent)}")

    keys = {
        "LANGFUSE_HOST": HOST,
        "LANGFUSE_PUBLIC_KEY": values["LANGFUSE_PUBLIC_KEY"],
        "LANGFUSE_SECRET_KEY": values["LANGFUSE_SECRET_KEY"],
    }
    set_keys(ROOT_ENV, keys, template=ROOT_ENV_EXAMPLE)
    print(f"Set LANGFUSE_* in {ROOT_ENV.name} (repo root)")

    sys.stdout.reconfigure(encoding="utf-8")
    print(
        "\nNext:\n"
        "  cd langfuse && docker compose up -d     # first start: ~2-3 min to pull and migrate\n"
        f"  open http://localhost:3000  ·  login {values['LANGFUSE_ADMIN_EMAIL']}"
        f"  ·  password in langfuse/.env (LANGFUSE_ADMIN_PASSWORD)"
    )
